function buildGlossaryTermIndex() {
  const seen = new Set();
  const termPairs = [];

  for (const [key, entry] of Object.entries(GLOSSARY)) {
    const terms = [entry.title, ...(entry.aliases || [])].filter(Boolean);
    for (const term of terms) {
      const normalized = term.toLowerCase();
      if (seen.has(normalized)) continue;
      seen.add(normalized);
      termPairs.push([term, key]);
    }
  }

  termPairs.sort((a, b) => b[0].length - a[0].length || a[0].localeCompare(b[0]));
  return termPairs;
}

function buildAliasRegex(termPairs = GLOSSARY_TERM_INDEX) {
  const escaped = termPairs.map(([alias]) => alias.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
  return new RegExp(`(?<![A-Za-z0-9])(${escaped.join("|")})(?![A-Za-z0-9])`, "gi");
}

const GLOSSARY_TERM_INDEX = buildGlossaryTermIndex();
const ALIAS_REGEX = buildAliasRegex();
const ALIAS_TO_KEY = new Map(GLOSSARY_TERM_INDEX.map(([alias, key]) => [alias.toLowerCase(), key]));


function annotateTerms(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      const parent = node.parentElement;
      if (!parent) return NodeFilter.FILTER_REJECT;
      if (parent.closest(".term, .term-preview, script, style, code, pre, textarea, button, a, svg")) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  const textNodes = [];
  while (walker.nextNode()) textNodes.push(walker.currentNode);

  for (const node of textNodes) {
    const text = node.nodeValue;
    if (!ALIAS_REGEX.test(text)) continue;
    ALIAS_REGEX.lastIndex = 0;
    const frag = document.createDocumentFragment();
    let last = 0;
    text.replace(ALIAS_REGEX, (match, term, offset) => {
      if (offset > last) frag.appendChild(document.createTextNode(text.slice(last, offset)));
      const key = ALIAS_TO_KEY.get(term.toLowerCase());
      const span = document.createElement("span");
      span.className = "term";
      span.tabIndex = 0;
      span.dataset.termKey = key;
      span.textContent = match;
      frag.appendChild(span);
      last = offset + match.length;
      return match;
    });
    if (last < text.length) frag.appendChild(document.createTextNode(text.slice(last)));
    node.parentNode.replaceChild(frag, node);
  }
}

function initTermPreview() {
  const preview = document.createElement("div");
  preview.className = "term-preview";
  preview.innerHTML = '<img alt=""><div class="title"></div><div class="meta"></div>';
  document.body.appendChild(preview);

  function showFor(el, x, y) {
    const key = el.dataset.termKey;
    const entry = GLOSSARY[key];
    if (!entry) return;
    preview.querySelector(".title").textContent = entry.title;
    preview.querySelector(".meta").textContent = entry.subtitle || "";
    const img = preview.querySelector("img");
    img.src = entry.img || placeholderSvg(entry.title, entry.subtitle || "");
    img.alt = entry.title;
    preview.classList.add("open");
    positionPreview(x, y);
  }

  function positionPreview(x, y) {
    const pad = 18;
    const box = preview.getBoundingClientRect();
    let left = x + 18;
    let top = y + 18;
    if (left + box.width > window.innerWidth - pad) left = x - box.width - 18;
    if (top + box.height > window.innerHeight - pad) top = y - box.height - 18;
    preview.style.left = Math.max(pad, left) + "px";
    preview.style.top = Math.max(pad, top) + "px";
  }

  document.addEventListener("mouseover", (e) => {
    const term = e.target.closest(".term");
    if (!term) return;
    showFor(term, e.clientX, e.clientY);
  });
  document.addEventListener("mousemove", (e) => {
    if (preview.classList.contains("open")) positionPreview(e.clientX, e.clientY);
  });
  document.addEventListener("mouseout", (e) => {
    if (e.target.closest(".term")) preview.classList.remove("open");
  });
  document.addEventListener("focusin", (e) => {
    const term = e.target.closest(".term");
    if (!term) return;
    const rect = term.getBoundingClientRect();
    showFor(term, rect.right, rect.bottom);
  });
  document.addEventListener("focusout", (e) => {
    if (e.target.closest(".term")) preview.classList.remove("open");
  });
}

function blockersDone(taskId, progress) {
  const blockers = (TASK_META[taskId] && TASK_META[taskId].blockers) || [];
  return blockers.every(id => progress[id]);
}

function blockerShortLabel(taskId) {
  const blocker = TASK_META[taskId];
  if (!blocker) return "required task";
  return blocker.title
    .replace(/^Task\s+(\d+):\s+.*$/, "Task $1")
    .replace(/^Task\s+(\d+).*$/, "Task $1");
}

function getTaskPageStatusBadges(task, progress = getProgress()) {
  if (!task) {
    return [];
  }

  if (progress[task.id]) {
    return [{ label: "Done", className: "status-chip status-done" }];
  }

  if (blockersDone(task.id, progress)) {
    return [{ label: "Ready now", className: "status-chip status-ready" }];
  }

  return (task.blockers || [])
    .filter(id => !progress[id])
    .map(id => ({
      label: `Blocked by ${blockerShortLabel(id)}`,
      className: "status-chip status-blocked"
    }));
}

